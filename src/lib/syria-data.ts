/** Get cities for a specific governorate */
export function getCitiesForGovernorate(governorateName: string): string[] {
  const gov = SYRIAN_GOVERNORATES.find(g => g.name === governorateName);
  return gov?.cities || [];
}

/** Get all governorate names */
export function getGovernorateNames(): string[] {
  return SYRIAN_GOVERNORATES.map(g => g.name);
}
